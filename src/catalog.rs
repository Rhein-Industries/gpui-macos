/// Find a component by its stable gallery identifier.
pub fn component(id: &str) -> Option<&'static ComponentInfo> {
    COMPONENTS.iter().find(|item| item.id == id)
}

impl ComponentInfo {
    /// The explicit native counterpart or macOS workflow interpretation.
    pub fn interpretation(&self) -> &'static crate::interpretation::ComponentInterpretation {
        crate::interpretation::interpretation(self.id)
            .expect("every catalog page has a presentation contract")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn component_inventory_is_complete_and_unique() {
        let ids: std::collections::HashSet<_> = COMPONENTS.iter().map(|item| item.id).collect();
        assert_eq!(ids.len(), COMPONENTS.len());
        assert!(COMPONENTS.len() >= 90);
        let grouped: Vec<_> = COMPONENT_GROUPS
            .iter()
            .flat_map(|(_, ids)| ids.iter().copied())
            .collect();
        assert_eq!(grouped.len(), COMPONENTS.len());
        assert_eq!(
            grouped
                .iter()
                .copied()
                .collect::<std::collections::HashSet<_>>(),
            ids
        );
        assert!(
            COMPONENTS
                .iter()
                .all(|item| !item.name.is_empty() && !item.description.is_empty())
        );
    }
}

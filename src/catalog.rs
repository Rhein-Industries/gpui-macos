//! Complete, discoverable component inventory used by the native gallery.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ComponentCategory {
    Explore,
    Actions,
    Forms,
    Navigation,
    Overlays,
    Display,
    Messages,
    MacOsLayouts,
    Charts,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ComponentInfo {
    pub id: &'static str,
    pub name: &'static str,
    pub category: ComponentCategory,
    pub description: &'static str,
    /// The GPUI Kit documentation slug, or `None` when there is no dedicated upstream page.
    pub documentation: Option<&'static str>,
}

